#!/usr/bin/env python3
"""Converts a table of Lucide icon paths (SVG path syntax on the 24x24 grid) into src/BitByBit.App/Theming/IconPaths.g.cs.

Input: a JS/JSON-like file with lines  "name": "<svg path>",  (e.g. a generated Icons.js table built from lucide-static).
The output uses explicit command letters for every segment and space-separated numbers, so WPF's path mini-language
(which is stricter than SVG about implicit repetitions and packed numbers such as "1.5.5" or arc flags) parses it.
Lucide is ISC licensed (third-party/lucide/LICENSE).
"""
import re
import sys

NUM = re.compile(r'[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?')
ARGS = {'m': 2, 'l': 2, 'h': 1, 'v': 1, 'c': 6, 's': 4, 'q': 4, 't': 2, 'a': 7, 'z': 0}


def tokens(d):
    i = 0
    while i < len(d):
        ch = d[i]
        if ch.isspace() or ch == ',':
            i += 1
        elif ch.lower() in ARGS and ch.isalpha():
            yield ch
            i += 1
        else:
            m = NUM.match(d, i)
            if not m:
                raise ValueError(f'bad path near {d[i:i+12]!r}')
            yield m.group(0)
            i = m.end()


def flag_split(tok):
    """Arc flags may be packed ("01", "1.5" after a flag): split a token into a single-digit flag and the rest."""
    return tok[0], tok[1:]


def fmt(x):
    v = float(x)
    s = f'{v:.3f}'.rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s


def convert(d):
    out = []
    toks = list(tokens(d))
    i = 0
    cmd = None
    first = True
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t
            i += 1
            if cmd.lower() == 'z':
                out.append('Z')
                continue
        elif cmd is None:
            raise ValueError('path does not start with a command')
        n = ARGS[cmd.lower()]
        args = []
        while len(args) < n:
            tok = toks[i]
            i += 1
            if cmd.lower() == 'a' and len(args) in (3, 4) and len(tok) > 1 and tok[0] in '01' and not tok.startswith(('0.', '1.')):
                f, rest = flag_split(tok)
                args.append(f)
                if rest:
                    toks.insert(i, rest)
                continue
            args.append(tok)
        letter = cmd
        if first and cmd == 'm':
            letter = 'M'
        first = False
        out.append(letter + ' ' + ' '.join(fmt(a) for a in args))
        # Implicit repetition after a moveto is a lineto.
        if cmd == 'M':
            cmd = 'L'
        elif cmd == 'm':
            cmd = 'l'
    return ' '.join(out)


def main(src, dst):
    entries = re.findall(r'"([a-z0-9-]+)"\s*:\s*"([^"]+)"', open(src, encoding='utf-8').read())
    lines = [
        '// <auto-generated> by scripts/convert-icons.py from Lucide icons (ISC licence, third-party/lucide/LICENSE). Do not edit.',
        'namespace BitByBit.App.Theming;',
        '',
        '/// <summary>Lucide line icons as WPF path data on a 24×24 grid, drawn with a stroke by <see cref="Icon"/>.</summary>',
        'public static partial class IconPaths',
        '{',
        '    public static IReadOnlyDictionary<string, string> All { get; } = new Dictionary<string, string>(StringComparer.Ordinal)',
        '    {',
    ]
    for name, d in sorted(entries):
        lines.append(f'        ["{name}"] = "{convert(d)}",')
    lines += ['    };', '}', '']
    open(dst, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'{len(entries)} icons written to {dst}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
